    def _make_tree_removable(self) -> None:
        if not self.root.exists():
            return
        for path in self.root.rglob("*"):
            if path.is_dir():
                path.chmod(0o755)
            else:
                path.chmod(0o644)

    @staticmethod
    def _sha(path: Path) -> str:
        return hashlib.sha256(path.read_bytes()).hexdigest()

    @staticmethod
    def _write_json(path: Path, value: object) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    @staticmethod
    def _header(command: str) -> str:
        return (
            "###############################################################\n"
            "#  Generated by:      Cadence Innovus 21.10-p004_1\n"
            "#  OS:                Linux x86_64\n"
            "#  Generated on:      Mon Jul 20 12:00:00 2026\n"
            "#  Design:            NV_NVDLA_CMAC_CORE_mac\n"
            f"#  Command:           {command}\n"
            "###############################################################\n"
        )

    def _timing(self, check: str, view: str, slack: float) -> str:
        status = "VIOLATED" if slack < 0.0 else "MET"
        # Real Innovus 21.10 setup reports use ``= Slack Time`` while hold
        # reports use ``  Slack Time`` without the equals sign.
        slack_prefix = "= " if check == "setup" else "  "
        return self._header(f"report_timing -{check}") + (
            f"Path 1: {status} {check.title()} Check with Pin u_capture/CK\n"
            "Endpoint:   u_capture/D (^) checked with leading edge of 'clk'\n"
            "Beginpoint: u_launch/Q (^) triggered by leading edge of 'clk'\n"
            "Path Groups: {clk}\n"
            f"Analysis View: {view}\n"
            f"{slack_prefix}Slack Time                    {slack:.3f}\n"
        )

    def _drv(self, transition_count: int = 0) -> str:
        if transition_count:
            transition = "\n".join(
                f"u_drv_{index}/Y 0.100 0.200 -0.100"
                for index in range(transition_count)
            )
        else:
            transition = "No paths found"
        return self._header("report_constraint -all_violators") + (
            "Check type : max_transition\n"
            "Pin Name Required Actual Slack\n"
            f"{transition}\n"
            "Check type : max_capacitance\n"
            "No violations were found\n"
            "Check type : max_fanout\n"
            "No paths found\n"
        )

    def _connectivity(self) -> str:
        return self._header("verifyConnectivity -type all") + (
            "Verify Connectivity Report\n"
            "Begin Summary\n"
            "    Found no problems or warnings.\n"
            "End Summary\n"
        )

    def _drc(self, count: int = 1) -> str:
        details = "" if count == 0 else "SHORT: ( Metal Short ) Regular Wire of Net a & Net b ( M1 )\n"
        return (
            self._header("verify_drc -limit 1000000 -report drc.rpt")
            + details
            + f"  Total Violations : {count} Viols.\n"
        )

